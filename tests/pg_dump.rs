#[test]
fn a_dump_restores_into_chronos_and_dumps_the_same() {
    if !tool("pg_dump") || !tool("psql") {
        eprintln!("skipped: no pg_dump or psql");
        return;
    }
    let (a, b) = (Server::start("pgdump-a"), Server::start("pgdump-b"));
    let (ok, text) = psql_file(a.port, &fixture());
    assert!(ok, "loading the schema failed:\n{text}");
    let first = pg_dump(a.port, &[]);
    let script = std::env::temp_dir().join(format!("chronos-pgdump-{}.sql", std::process::id()));
    std::fs::write(&script, &first).unwrap();
    let (ok, text) = psql_file(b.port, &script);
    let _ = std::fs::remove_file(&script);
    assert!(ok, "restoring the dump failed:\n{text}");
    // the same objects, the same rows, the same counters: a second dump of what was restored is the first
    assert_eq!(stable(&pg_dump(b.port, &[])), stable(&first));
}

#[test]
fn a_dump_restores_into_postgres() {
    if !tool("pg_dump") || !tool("psql") {
        eprintln!("skipped: no pg_dump or psql");
        return;
    }
    let pg = |args: &[&str]| {
        Command::new("psql")
            .args(["-X", "-q", "-h", "/tmp", "-U", "postgres", "-v", "ON_ERROR_STOP=1"])
            .args(args)
            .stdin(Stdio::null())
            .output()
            .unwrap()
    };
    let name = format!("chronos_dump_{}", std::process::id());
    if !pg(&["-d", "postgres", "-c", &format!("create database {name}")]).status.success() {
        eprintln!("skipped: no Postgres at host=/tmp");
        return;
    }
    let s = Server::start("pgdump-pg");
    let (ok, text) = psql_file(s.port, &fixture());
    assert!(ok, "loading the schema failed:\n{text}");
    let script = std::env::temp_dir().join(format!("chronos-pgdump-pg-{}.sql", std::process::id()));
    std::fs::write(&script, pg_dump(s.port, &["--no-owner"])).unwrap();
    let restored = pg(&["-d", &name, "-f", script.to_str().unwrap()]);
    let _ = std::fs::remove_file(&script);
    let said = format!("{}{}", String::from_utf8_lossy(&restored.stdout), String::from_utf8_lossy(&restored.stderr));
    let ask = |sql: &str| {
        let out = pg(&["-d", &name, "-At", "-c", sql]);
        String::from_utf8_lossy(&out.stdout).trim().to_string()
    };
    let rows = ask("select (select count(*) from app.accounts) || ',' || (select count(*) from app.tickets) || ',' \
         || (select count(*) from app.counts) || ',' || (select sum(n) from app.counts) || ',' \
         || (select string_agg(code || ':' || balance, ' ' order by id) from app.accounts) || ',' \
         || app.bump(41) || ',' || (select nextval('app.ticket_no'))");
    let _ = pg(&["-d", "postgres", "-c", &format!("drop database {name}")]);
    assert!(restored.status.success(), "Postgres couldn't restore the dump:\n{said}");
    // (each row a ticket the trigger stamped, the sequence where Chronos left it: 1010, so the next is 1015)
    assert_eq!(rows, "2,3,2,3,A1:10.50 B2:0.00,42,1015");
}

/// psql on the Chronos server at `port`, one query, unaligned: its rows.
fn psql_query(port: u16, sql: &str) -> String {
    let out = Command::new("psql")
        .args(["-X", "-q", "-A", "-t", "-h", "127.0.0.1", "-p", &port.to_string(), "-U", "postgres", "-c", sql, "main"])
        .stdin(Stdio::null())
        .output()
        .unwrap();
    format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr))
}

/// A dump restores reg values to the objects they named: a restore copies a table's rows before it makes the
/// indexes and constraints, and a regclass, regclass[], regtype of an enum and regnamespace read then name the same
/// objects once those are made, with their unique index finding them.
#[test]
fn a_dump_restores_reg_values_to_their_objects() {
    if !tool("pg_dump") || !tool("psql") {
        eprintln!("skipped: no pg_dump or psql");
        return;
    }
    let (a, b) = (Server::start("pgdump-reg-a"), Server::start("pgdump-reg-b"));
    let setup = "create schema rgd_s; create type rgd_mood as enum ('a'); create table rgd_t (id int primary key); \
                 create table rgd_a (id int primary key, v text unique); \
                 create table rgd_k (id int primary key, r regclass unique, rs regclass[], t regtype, n regnamespace); \
                 insert into rgd_k values (1, 'rgd_t', '{rgd_t,rgd_a}', 'rgd_mood', 'rgd_s'), (2, 'rgd_a', null, 'int4', null)";
    let script = std::env::temp_dir().join(format!("chronos-pgdump-reg-{}.sql", std::process::id()));
    std::fs::write(&script, setup).unwrap();
    let (ok, text) = psql_file(a.port, &script);
    assert!(ok, "loading failed:\n{text}");
    let want = "1|rgd_t|{rgd_t,rgd_a}|rgd_mood|rgd_s\n2|rgd_a||integer|\n";
    let q = "select id, r, rs, t, n from rgd_k order by id";
    assert_eq!(psql_query(a.port, q), want);
    std::fs::write(&script, pg_dump(a.port, &[])).unwrap();
    let (ok, text) = psql_file(b.port, &script);
    let _ = std::fs::remove_file(&script);
    assert!(ok, "restoring the dump failed:\n{text}");
    assert_eq!(psql_query(b.port, q), want);
    assert_eq!(psql_query(b.port, "select id from rgd_k where r = 'rgd_t'::regclass"), "1\n");
    assert!(psql_query(b.port, "insert into rgd_k values (3, 'rgd_t')").contains("duplicate key"));
}
