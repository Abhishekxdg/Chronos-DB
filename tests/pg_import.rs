/// A materialized view Postgres holds unpopulated (`WITH NO DATA`, relispopulated false; Pagila's
/// rental_by_category) comes over unpopulated: reading it is 55000, as in Postgres, until REFRESH fills it. A
/// populated one beside it is filled.
#[test]
fn an_unpopulated_materialized_view_stays_unpopulated() {
    let Some((mut admin, name, url)) = throwaway("matview_nodata") else {
        eprintln!("skipped: set CHRONOS_TEST_PG to a Postgres URL");
        return;
    };
    let mut pg = postgres::Client::connect(&url, postgres::NoTls).unwrap();
    pg.batch_execute(
        "create table t (id int primary key, v text);
         insert into t values (1, 'A'), (2, 'b');
         create materialized view empty_mv as select id, v from t with no data;
         create unique index empty_mv_id on empty_mv (id);
         create materialized view full_mv as select id from t;",
    )
    .unwrap();
    drop(pg);

    let dir = std::env::temp_dir().join(format!("chronos-pg-import-matview-nodata-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let (ok, out) = import(&url, &dir);
    assert!(ok, "{out}");
    let db = Db::open(&dir).unwrap();
    let e = run(&db, MAIN, "select count(*) from empty_mv", &[]).unwrap_err();
    assert_eq!(e.code, "55000", "{e}: {out}");
    assert!(e.message.starts_with("materialized view \"empty_mv\" has not been populated"), "{e}");
    assert_eq!(cell(&db, "select relispopulated from pg_class where relname = 'empty_mv'"), "false");
    assert_eq!(cell(&db, "select count(*) from pg_indexes where tablename = 'empty_mv'"), "1", "{out}");
    assert_eq!(cell(&db, "select count(*) from full_mv"), "2");
    run(&db, MAIN, "refresh materialized view empty_mv", &[]).unwrap();
    assert_eq!(cell(&db, "select count(*) from empty_mv"), "2");
    drop(db);
    std::fs::remove_dir_all(&dir).unwrap();
    admin.batch_execute(&format!("drop database {name}")).unwrap();
}

